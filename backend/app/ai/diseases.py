def find_relevant(text: str, limit: int = 5) -> list[Disease]:
    """Diseases whose names or key symptoms appear in the text, best match first."""
    t = " " + " ".join(text.lower().split()) + " "
    scored = []
    for d in DISEASES:
        score = sum(3 for n in d.names if n.lower() in t) + sum(1 for m in d.match if m.lower() in t)
        if score:
            scored.append((score, d))
    scored.sort(key=lambda x: -x[0])
    return [d for _, d in scored[:limit]]


def reference_notes(text: str, limit: int = 5) -> str:
    """Short reference block for the AI prompt ("" when nothing matches)."""
    found = find_relevant(text, limit)
    if not found:
        return ""
    lines = ["Reference notes from the app's checked disease knowledge base (use them to guide your "
             "questions and causes; they are background, not a diagnosis; the user's answers decide):"]
    for d in found:
        lines.append(f"* {d.name}: typical: {d.symptoms} Danger signs: {d.red_flags} Tests: {d.tests}. "
                     f"Doctor: {d.specialist}. Self-care: {d.self_care}")
    return "\n".join(lines)
