"""Disease knowledge base for the AI assistant and the symptom check.

We do not train the AI model itself. Instead, the backend keeps this checked list of 50 common and
important diseases in Pakistan (key symptoms, danger signs, useful tests, the right specialist and
self-care), finds the entries that match what the user wrote, and gives them to the AI as reference
notes. For any disease not in the list the AI uses its general medical knowledge, with the same
safety rules (red flags first, no diagnosis, no doses).

`match` holds English, Roman Urdu and Urdu words; a disease's own name counts more than a symptom.
"""
from dataclasses import dataclass


